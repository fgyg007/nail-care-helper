const { test, expect } = require('@playwright/test');
test('offline assets, check-ins, map, photo persistence and calendar export', async ({ page, context }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => route.request().url().startsWith('http://127.0.0.1:4173') ? route.continue() : route.abort());
  await page.goto('/');
  await expect(page.locator('header')).toHaveCSS('background-color', 'rgb(13, 148, 136)');
  await page.locator('#chk-amorolfine').check();
  await page.locator('#stage-btn-2').click();
  await page.reload();
  await expect(page.locator('#chk-amorolfine')).toBeChecked();
  await expect(page.locator('#statDays')).toHaveText('1');
  await expect(page.locator('#stageTitle')).toContainText('阶段2');
  await page.locator('#nav-map').click();
  await page.locator('#node-LF1').click();
  await page.reload();
  await expect(page.locator('#statNails')).toHaveText('2');
  await page.locator('#photoNote').fill('<img src=x onerror=alert(1)>');
  await page.locator('#photoFile').setInputFiles({ name: 'test.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aD1sAAAAASUVORK5CYII=', 'base64') });
  await expect(page.locator('#statPhotos')).toHaveText('1');
  await page.reload();
  await expect(page.locator('#statPhotos')).toHaveText('1');
  await page.locator('#nav-gallery').click();
  await expect(page.locator('#allPhotosTimeline')).toContainText('<img src=x onerror=alert(1)>');
  await expect(page.locator('#allPhotosTimeline img')).toHaveCount(1);
  await page.locator('#nav-guide').click();
  await expect(page.locator('#tab-guide')).toBeVisible();
  await page.getByRole('button', { name: '🔔 手机强提醒' }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '生成并分享日历文件' }).click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  const chunks = []; for await (const chunk of stream) chunks.push(chunk);
  const ics = Buffer.concat(chunks).toString();
  expect(ics.match(/UID:/g)).toHaveLength(3);
  expect(ics).toContain('RRULE:FREQ=DAILY;COUNT=90');
  await page.locator('#nav-today').click();
  await page.screenshot({ path: 'test-results/today.png', fullPage: true });
  await context.setOffline(true);
  await page.locator('#nav-map').click();
  await expect(page.locator('#tab-map')).toBeVisible();
  expect(errors).toEqual([]);
});
